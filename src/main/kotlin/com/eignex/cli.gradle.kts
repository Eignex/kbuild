import com.eignex.kbuild.EignexCliExtension
import com.eignex.kbuild.KBUILD_JVM_TOOLCHAIN
import com.eignex.kbuild.applyKbuildCommonDependencies
import java.security.MessageDigest
import org.jetbrains.kotlin.gradle.ExperimentalKotlinGradlePluginApi
import org.jetbrains.kotlin.gradle.plugin.mpp.Executable
import org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget
import org.jetbrains.kotlin.gradle.plugin.mpp.NativeBuildType
import org.jetbrains.kotlin.gradle.targets.jvm.KotlinJvmTarget
import org.jetbrains.kotlin.konan.target.HostManager

plugins {
    kotlin("multiplatform")
    id("org.jetbrains.kotlinx.kover")
}

apply(plugin = "com.eignex.lint")

group = "com.eignex"
version = findProperty("ciVersion") as String? ?: "SNAPSHOT"

repositories { mavenCentral() }

val eignexCli = extensions.create<EignexCliExtension>("eignexCli")

kotlin {
    jvmToolchain(KBUILD_JVM_TOOLCHAIN)

    // Declare targets in your build.gradle.kts:
    //   jvm()
    //   linuxX64(); macosX64(); macosArm64()
    // The executable conventions below apply to whatever targets exist.

    applyKbuildCommonDependencies(project)
}

// --version build identity: an `internal object BuildInfo` generated into commonMain, so every
// target shares it and no CLI hand-maintains a constant that drifts. It lands under build/ and
// is internal, so neither the detekt/checkKdoc `src` scan nor dokka sees it.
val generatedBuildInfoDir = layout.buildDirectory.dir("generated/eignexCliBuildInfo/kotlin")
// Plain Strings captured at configuration time (CC-safe defaults).
val projectVersion = version.toString()
val projectName = name
val projectGroup = group.toString()

val generateCliBuildInfo = tasks.register("generateCliBuildInfo") {
    description = "Generates the BuildInfo object (NAME/ID/VERSION) the CLI reports via --version."
    val outDir = generatedBuildInfoDir
    // Lazy: the consumer configures eignexCli after this plugin applies, so resolve at
    // execution time, with orElse supplying the project-derived default.
    val versionValue = eignexCli.version.orElse(projectVersion)
    val nameValue = eignexCli.appName.orElse(projectName)
    val idValue = eignexCli.appId.orElse(projectGroup)
    val packageValue = eignexCli.buildInfoPackage
        .orElse(eignexCli.mainClass.map { it.substringBeforeLast('.') })
        .orElse(projectGroup)
    inputs.property("version", versionValue)
    inputs.property("name", nameValue)
    inputs.property("id", idValue)
    inputs.property("package", packageValue)
    outputs.dir(outDir)
    doLast {
        fun esc(s: String) = s.replace("\\", "\\\\").replace("\"", "\\\"")
        val pkg = packageValue.get()
        val file = outDir.get().asFile.resolve(pkg.replace('.', '/') + "/BuildInfo.kt")
        file.parentFile.mkdirs()
        file.writeText(
            buildString {
                appendLine("package $pkg")
                appendLine()
                appendLine("/** Build identity reported by the `--version` flag. Generated by com.eignex.cli; do not edit. */")
                appendLine("internal object BuildInfo {")
                appendLine("    /** Human-facing application name. */")
                appendLine("    const val NAME: String = \"${esc(nameValue.get())}\"")
                appendLine()
                appendLine("    /** Reverse-DNS application id. */")
                appendLine("    const val ID: String = \"${esc(idValue.get())}\"")
                appendLine()
                appendLine("    /** Project version string. */")
                appendLine("    const val VERSION: String = \"${esc(versionValue.get())}\"")
                appendLine()
                appendLine("    /** Single line for `--version` output, in `name version` form. */")
                appendLine("    fun versionLine(): String = \"\$NAME \$VERSION\"")
                appendLine("}")
            },
        )
    }
}

// srcDir(taskProvider) adds the dir and makes every target's compilation depend on the task.
kotlin.sourceSets.named("commonMain") {
    kotlin.srcDir(generateCliBuildInfo)
}

// Eager all {}, not configureEach: the binaries DSL applies the distribution plugin,
// which calls afterEvaluate — forbidden inside lazy configuration actions.
kotlin.targets.withType<KotlinJvmTarget>().all {
    @OptIn(ExperimentalKotlinGradlePluginApi::class)
    binaries {
        executable {
            mainClass.set(eignexCli.mainClass)
        }
    }
}

// Everything below reads consumer configuration that exists only after their script has run.
afterEvaluate {
    // entryPoint is a plain var on the binary, not a property, so it cannot take a provider.
    kotlin.targets.withType<KotlinNativeTarget>().configureEach {
        binaries.executable {
            eignexCli.entryPoint.orNull?.let { entryPoint = it }
        }
    }

    // Release packaging: renamed, stripped native executables plus the JVM dist zip, collected
    // into build/release-assets/ for upload to a GitHub release.
    val baseName = project.name
    val assetVersion = version.toString()
    val assetsDir = layout.buildDirectory.dir("release-assets")

    // Only host-linkable targets: macOS binaries cannot be cross-linked from Linux and vice versa.
    val hostManager = HostManager()
    val nativeExecutables = kotlin.targets.withType<KotlinNativeTarget>()
        .filter { hostManager.isEnabled(it.konanTarget) }
        .flatMap { it.binaries.filterIsInstance<Executable>() }
        .filter { it.buildType == NativeBuildType.RELEASE }
    val jvmDistZip = tasks.findByName("jvmDistZip") as Zip?

    tasks.register("releaseAssets") {
        group = "distribution"
        description = "Collects stripped native executables and the JVM dist zip into build/release-assets."
        nativeExecutables.forEach { dependsOn(it.linkTaskProvider) }
        jvmDistZip?.let { dependsOn(it) }

        val nativeAssets = nativeExecutables.map { binary ->
            // linux_x64 -> linux-x64, mingw_x64 -> windows-x64
            val osArch = binary.target.konanTarget.name.replace("mingw", "windows").replace('_', '-')
            binary.outputFile to "$baseName-$assetVersion-$osArch"
        }
        val jvmZip = jvmDistZip?.archiveFile
        // macOS needs -x (non-global symbols only): a full strip fails on linked Mach-O executables.
        val stripCommand = if (HostManager.hostIsMac) listOf("strip", "-x") else listOf("strip")

        doLast {
            val dir = assetsDir.get().asFile
            dir.deleteRecursively()
            dir.mkdirs()
            val assets = mutableListOf<File>()
            for ((outputFile, assetName) in nativeAssets) {
                val asset = outputFile.copyTo(dir.resolve(assetName))
                asset.setExecutable(true)
                // Best effort: keep the unstripped binary if strip is unavailable.
                // Discard output: an unread pipe fills up and deadlocks waitFor.
                runCatching {
                    ProcessBuilder(stripCommand + asset.absolutePath)
                        .redirectOutput(ProcessBuilder.Redirect.DISCARD)
                        .redirectError(ProcessBuilder.Redirect.DISCARD)
                        .start()
                        .waitFor()
                }
                assets += asset
            }
            jvmZip?.let { assets += it.get().asFile.copyTo(dir.resolve("$baseName-$assetVersion-jvm.zip")) }
            val digest = MessageDigest.getInstance("SHA-256")
            dir.resolve("SHA256SUMS").writeText(
                assets.joinToString("") { asset ->
                    val sum = digest.digest(asset.readBytes()).joinToString("") { "%02x".format(it) }
                    "$sum  ${asset.name}\n"
                }
            )
        }
    }
}
